defmodule TSC.Resolver.NodeModulesResolver do
  @moduledoc """
  Node.js-style module resolution for TypeScript projects.

  Handles:
  - Bare module specifiers (lodash, react)
  - Scoped packages (@scope/package)
  - package.json entry point resolution (types, typings, main)
  - @types/* package lookup for TypeScript definitions
  - Directory tree walking to find node_modules
  """

  require Logger

  @type_extensions [".d.ts", ".ts", ".tsx"]
  @js_extensions [".js", ".jsx"]
  @index_files ["index.d.ts", "index.ts", "index.tsx", "index.js"]

  @doc """
  Resolve a bare module specifier to an absolute file path.

  Returns {:ok, path} if found, :not_found otherwise.

  ## Examples

      iex> resolve("lodash", "/project/src/index.ts")
      {:ok, "/project/node_modules/lodash/index.d.ts"}

      iex> resolve("@types/node", "/project/src/index.ts")
      {:ok, "/project/node_modules/@types/node/index.d.ts"}
  """
  @spec resolve(String.t(), String.t()) :: {:ok, String.t()} | :not_found
  def resolve(specifier, from_file) do
    from_dir = Path.dirname(from_file)
    {package_name, subpath} = parse_package_name(specifier)

    # Resolution strategy:
    # 1. Check @types/<package> first (highest priority for TypeScript)
    # 2. Check package for TypeScript files (.d.ts, .ts)
    # 3. Fall back to JavaScript files (.js) only if no TS files found

    # First try @types/<package> (only for non-scoped packages that aren't already @types)
    types_result = unless String.starts_with?(package_name, "@") do
      case find_package_in_node_modules("@types/#{package_name}", from_dir) do
        {:ok, types_dir} ->
          resolve_package_entry_typescript_only(types_dir, subpath)
        :not_found ->
          :not_found
      end
    else
      :not_found
    end

    case types_result do
      {:ok, _} = ok -> ok
      :not_found ->
        # Try the package itself
        case find_package_in_node_modules(package_name, from_dir) do
          {:ok, package_dir} ->
            # First try TypeScript files only
            case resolve_package_entry_typescript_only(package_dir, subpath) do
              {:ok, _} = ok -> ok
              :not_found ->
                # Fall back to JS files (for allowJs scenarios)
                resolve_package_entry_js_only(package_dir, subpath)
            end

          :not_found ->
            :not_found
        end
    end
  end

  @doc """
  Parse a package specifier into package name and optional subpath.

  Handles scoped packages (@scope/package) and subpaths (package/lib/foo).

  ## Examples

      iex> parse_package_name("lodash")
      {"lodash", nil}

      iex> parse_package_name("lodash/fp")
      {"lodash", "fp"}

      iex> parse_package_name("@types/node")
      {"@types/node", nil}

      iex> parse_package_name("@scope/package/lib")
      {"@scope/package", "lib"}
  """
  @spec parse_package_name(String.t()) :: {String.t(), String.t() | nil}
  def parse_package_name(specifier) do
    parts = String.split(specifier, "/")

    case parts do
      # Scoped package: @scope/package or @scope/package/subpath
      ["@" <> _scope = scope, package | rest] ->
        package_name = "#{scope}/#{package}"
        subpath = if rest == [], do: nil, else: Enum.join(rest, "/")
        {package_name, subpath}

      # Regular package: package or package/subpath
      [package | rest] ->
        subpath = if rest == [], do: nil, else: Enum.join(rest, "/")
        {package, subpath}

      [] ->
        {specifier, nil}
    end
  end

  @doc """
  Walk up the directory tree looking for node_modules/<package>.

  Starts from `from_dir` and walks up until finding node_modules
  with the specified package, or reaching the filesystem root.
  """
  @spec find_package_in_node_modules(String.t(), String.t()) :: {:ok, String.t()} | :not_found
  def find_package_in_node_modules(package_name, from_dir) do
    do_find_package(package_name, Path.expand(from_dir))
  end

  defp do_find_package(package_name, current_dir) do
    node_modules_path = Path.join(current_dir, "node_modules")
    package_path = Path.join(node_modules_path, package_name)

    cond do
      File.dir?(package_path) ->
        {:ok, package_path}

      # Reached filesystem root
      current_dir == "/" or current_dir == Path.dirname(current_dir) ->
        :not_found

      true ->
        # Walk up one directory
        do_find_package(package_name, Path.dirname(current_dir))
    end
  end

  @doc """
  Resolve the entry point for a package directory.

  Reads package.json and resolves the types/typings/main field,
  or falls back to index files.

  ## Resolution priority:
  1. Subpath if provided (e.g., package/lib/foo)
  2. package.json "types" field
  3. package.json "typings" field
  4. package.json "main" field (try .d.ts version)
  5. index.d.ts, index.ts, index.js in package root
  """
  @spec resolve_package_entry(String.t(), String.t() | nil) :: {:ok, String.t()} | :not_found
  def resolve_package_entry(package_dir, subpath) do
    if subpath do
      resolve_subpath(package_dir, subpath)
    else
      resolve_main_entry(package_dir)
    end
  end

  @doc """
  Resolve package entry looking only for TypeScript files (.d.ts, .ts, .tsx).
  """
  @spec resolve_package_entry_typescript_only(String.t(), String.t() | nil) :: {:ok, String.t()} | :not_found
  def resolve_package_entry_typescript_only(package_dir, subpath) do
    if subpath do
      resolve_subpath_typescript_only(package_dir, subpath)
    else
      resolve_main_entry_typescript_only(package_dir)
    end
  end

  @doc """
  Resolve package entry looking only for JavaScript files (.js, .jsx).
  """
  @spec resolve_package_entry_js_only(String.t(), String.t() | nil) :: {:ok, String.t()} | :not_found
  def resolve_package_entry_js_only(package_dir, subpath) do
    if subpath do
      resolve_subpath_js_only(package_dir, subpath)
    else
      resolve_main_entry_js_only(package_dir)
    end
  end

  defp resolve_subpath(package_dir, subpath) do
    base_path = Path.join(package_dir, subpath)

    # Try with various extensions
    extensions = @type_extensions ++ @js_extensions

    result =
      Enum.find_value(extensions, fn ext ->
        full_path = base_path <> ext

        if File.exists?(full_path) do
          {:ok, full_path}
        end
      end)

    case result do
      {:ok, _} = ok ->
        ok

      nil ->
        # Try as directory with index file
        Enum.find_value(@index_files, :not_found, fn index ->
          index_path = Path.join(base_path, index)

          if File.exists?(index_path) do
            {:ok, index_path}
          end
        end)
    end
  end

  defp resolve_main_entry(package_dir) do
    package_json_path = Path.join(package_dir, "package.json")

    case read_package_json(package_json_path) do
      {:ok, pkg} ->
        resolve_from_package_json(package_dir, pkg)

      :error ->
        # No package.json, try index files
        resolve_index_file(package_dir)
    end
  end

  defp resolve_from_package_json(package_dir, pkg) do
    # Try types field first
    cond do
      types = pkg["types"] ->
        resolve_entry_path(package_dir, types)

      typings = pkg["typings"] ->
        resolve_entry_path(package_dir, typings)

      main = pkg["main"] ->
        # Try .d.ts version of main
        resolve_main_with_dts(package_dir, main)

      true ->
        resolve_index_file(package_dir)
    end
  end

  defp resolve_entry_path(package_dir, entry) do
    # Handle ./ prefix
    entry = String.replace_leading(entry, "./", "")
    full_path = Path.join(package_dir, entry)

    if File.exists?(full_path) do
      {:ok, full_path}
    else
      # Try adding extensions
      extensions = @type_extensions ++ @js_extensions

      Enum.find_value(extensions, :not_found, fn ext ->
        path_with_ext = full_path <> ext

        if File.exists?(path_with_ext) do
          {:ok, path_with_ext}
        end
      end)
    end
  end

  defp resolve_main_with_dts(package_dir, main) do
    # Handle ./ prefix
    main = String.replace_leading(main, "./", "")

    # Try .d.ts version first
    base = String.replace_suffix(main, ".js", "")
    dts_path = Path.join(package_dir, base <> ".d.ts")

    if File.exists?(dts_path) do
      {:ok, dts_path}
    else
      # Try the main file directly
      main_path = Path.join(package_dir, main)

      if File.exists?(main_path) do
        {:ok, main_path}
      else
        resolve_index_file(package_dir)
      end
    end
  end

  defp resolve_index_file(package_dir) do
    Enum.find_value(@index_files, :not_found, fn index ->
      index_path = Path.join(package_dir, index)

      if File.exists?(index_path) do
        {:ok, index_path}
      end
    end)
  end

  @doc """
  Read and parse a package.json file.
  """
  @spec read_package_json(String.t()) :: {:ok, map()} | :error
  def read_package_json(path) do
    case File.read(path) do
      {:ok, content} ->
        case Jason.decode(content) do
          {:ok, pkg} -> {:ok, pkg}
          {:error, _} -> :error
        end

      {:error, _} ->
        :error
    end
  end

  # TypeScript-only resolution helpers

  defp resolve_subpath_typescript_only(package_dir, subpath) do
    base_path = Path.join(package_dir, subpath)

    # Try with TypeScript extensions only
    result =
      Enum.find_value(@type_extensions, fn ext ->
        full_path = base_path <> ext

        if File.exists?(full_path) do
          {:ok, full_path}
        end
      end)

    case result do
      {:ok, _} = ok ->
        ok

      nil ->
        # Try as directory with TypeScript index file
        ts_index_files = ["index.d.ts", "index.ts", "index.tsx"]
        Enum.find_value(ts_index_files, :not_found, fn index ->
          index_path = Path.join(base_path, index)

          if File.exists?(index_path) do
            {:ok, index_path}
          end
        end)
    end
  end

  defp resolve_main_entry_typescript_only(package_dir) do
    package_json_path = Path.join(package_dir, "package.json")

    case read_package_json(package_json_path) do
      {:ok, pkg} ->
        resolve_from_package_json_typescript_only(package_dir, pkg)

      :error ->
        # No package.json, try TypeScript index files
        resolve_index_file_typescript_only(package_dir)
    end
  end

  defp resolve_from_package_json_typescript_only(package_dir, pkg) do
    # Try types field first
    cond do
      types = pkg["types"] ->
        resolve_entry_path_typescript_only(package_dir, types)

      typings = pkg["typings"] ->
        resolve_entry_path_typescript_only(package_dir, typings)

      main = pkg["main"] ->
        # Try .d.ts version of main only
        resolve_main_dts_only(package_dir, main)

      true ->
        resolve_index_file_typescript_only(package_dir)
    end
  end

  defp resolve_entry_path_typescript_only(package_dir, entry) do
    # Handle ./ prefix
    entry = String.replace_leading(entry, "./", "")
    full_path = Path.join(package_dir, entry)

    if File.exists?(full_path) and String.ends_with?(full_path, @type_extensions) do
      {:ok, full_path}
    else
      # Try adding TypeScript extensions
      Enum.find_value(@type_extensions, :not_found, fn ext ->
        path_with_ext = full_path <> ext

        if File.exists?(path_with_ext) do
          {:ok, path_with_ext}
        end
      end)
    end
  end

  defp resolve_main_dts_only(package_dir, main) do
    # Handle ./ prefix
    main = String.replace_leading(main, "./", "")

    # Try .d.ts version only
    base = String.replace_suffix(main, ".js", "")
    dts_path = Path.join(package_dir, base <> ".d.ts")

    if File.exists?(dts_path) do
      {:ok, dts_path}
    else
      :not_found
    end
  end

  defp resolve_index_file_typescript_only(package_dir) do
    ts_index_files = ["index.d.ts", "index.ts", "index.tsx"]
    Enum.find_value(ts_index_files, :not_found, fn index ->
      index_path = Path.join(package_dir, index)

      if File.exists?(index_path) do
        {:ok, index_path}
      end
    end)
  end

  # JavaScript-only resolution helpers

  defp resolve_subpath_js_only(package_dir, subpath) do
    base_path = Path.join(package_dir, subpath)

    # Try with JS extensions only
    result =
      Enum.find_value(@js_extensions, fn ext ->
        full_path = base_path <> ext

        if File.exists?(full_path) do
          {:ok, full_path}
        end
      end)

    case result do
      {:ok, _} = ok ->
        ok

      nil ->
        # Try as directory with JS index file
        js_index_files = ["index.js", "index.jsx"]
        Enum.find_value(js_index_files, :not_found, fn index ->
          index_path = Path.join(base_path, index)

          if File.exists?(index_path) do
            {:ok, index_path}
          end
        end)
    end
  end

  defp resolve_main_entry_js_only(package_dir) do
    package_json_path = Path.join(package_dir, "package.json")

    case read_package_json(package_json_path) do
      {:ok, pkg} ->
        if main = pkg["main"] do
          resolve_entry_path_js_only(package_dir, main)
        else
          resolve_index_file_js_only(package_dir)
        end

      :error ->
        resolve_index_file_js_only(package_dir)
    end
  end

  defp resolve_entry_path_js_only(package_dir, entry) do
    # Handle ./ prefix
    entry = String.replace_leading(entry, "./", "")
    full_path = Path.join(package_dir, entry)

    if File.exists?(full_path) and String.ends_with?(full_path, @js_extensions) do
      {:ok, full_path}
    else
      # Try adding JS extensions
      Enum.find_value(@js_extensions, :not_found, fn ext ->
        path_with_ext = full_path <> ext

        if File.exists?(path_with_ext) do
          {:ok, path_with_ext}
        end
      end)
    end
  end

  defp resolve_index_file_js_only(package_dir) do
    js_index_files = ["index.js", "index.jsx"]
    Enum.find_value(js_index_files, :not_found, fn index ->
      index_path = Path.join(package_dir, index)

      if File.exists?(index_path) do
        {:ok, index_path}
      end
    end)
  end
end
