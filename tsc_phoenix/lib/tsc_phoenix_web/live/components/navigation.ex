defmodule TscPhoenixWeb.Live.Components.Navigation do
  @moduledoc """
  Shared navigation component for the TSC Dashboard.
  """

  use Phoenix.Component

  @nav_items [
    %{path: "/", label: "Dashboard", icon: "home"},
    %{path: "/errors", label: "Errors", icon: "exclamation-circle"},
    %{path: "/metrics", label: "Metrics", icon: "chart-bar"},
    %{path: "/graph", label: "Graph", icon: "share"},
    %{path: "/performance", label: "Performance", icon: "bolt"},
    %{path: "/cluster", label: "Cluster", icon: "server-stack"}
  ]

  attr :current_path, :string, default: "/"

  def nav_tabs(assigns) do
    assigns = assign(assigns, :nav_items, @nav_items)

    ~H"""
    <div class="tabs tabs-boxed bg-base-200">
      <%= for item <- @nav_items do %>
        <a
          href={item.path}
          class={"tab gap-2 #{if active?(@current_path, item.path), do: "tab-active"}"}
        >
          <.nav_icon name={item.icon} />
          <%= item.label %>
        </a>
      <% end %>
    </div>
    """
  end

  defp active?(current, path) when path == "/", do: current == "/"
  defp active?(current, path), do: String.starts_with?(current, path)

  defp nav_icon(assigns) do
    ~H"""
